import { useEffect } from 'react';
import { X } from 'lucide-react';
import type { OriginLanguage } from '../i18n';

interface ImageLightboxProps {
  imageUrl: string;
  language: OriginLanguage;
  onClose: () => void;
}

/**
 * 生成画像の拡大表示（品質検査 Q7-07、2026-11-28）。
 *
 * チャットの結果画像を押すと開く、見るだけのモーダル。既存の
 * ダイアログ（KenBurnsVideoDialog）の流儀に合わせる：外側の
 * origin-dialog-overlay を押すか、Esc か、閉じるボタンで閉じる。
 * 画像そのものは端末内の表示だけで、外部へは何も送らない。
 */
export default function ImageLightbox({ imageUrl, language, onClose }: ImageLightboxProps) {
  const ja = language === 'ja';
  const title = ja ? '画像の拡大表示' : 'Enlarged image';

  // Escape closes the dialog (same discipline as KenBurnsVideoDialog).
  useEffect(() => {
    const onKeyDown = (event: KeyboardEvent) => {
      if (event.key === 'Escape') onClose();
    };
    document.addEventListener('keydown', onKeyDown);
    return () => document.removeEventListener('keydown', onKeyDown);
  }, [onClose]);

  return (
    <div
      className="origin-dialog-overlay fixed inset-0 z-50 flex items-center justify-center p-4"
      onClick={onClose}
      role="presentation"
    >
      <section
        role="dialog"
        aria-modal="true"
        aria-label={title}
        data-testid="origin-image-lightbox"
        className="w-full max-w-3xl rounded-2xl border border-[var(--border-default)] bg-[var(--bg-surface)] p-4 shadow-xl"
        onClick={(event) => event.stopPropagation()}
      >
        <div className="flex items-center justify-between gap-2">
          <h2 className="text-sm font-bold">{title}</h2>
          <button
            type="button"
            onClick={onClose}
            aria-label={ja ? '閉じる' : 'Close'}
            className="origin-secondary-button origin-close-button"
          >
            <X aria-hidden="true" size={18} />
          </button>
        </div>
        <div className="mt-3 flex items-center justify-center overflow-hidden rounded-xl">
          <img
            src={imageUrl}
            alt={ja ? 'ORIGINが生成した画像' : 'Image generated by ORIGIN'}
            className="block h-auto max-h-[80vh] w-auto max-w-full object-contain"
          />
        </div>
      </section>
    </div>
  );
}
